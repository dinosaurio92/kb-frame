#!/usr/bin/env python3
"""build_map.py - regenerates <system>/MAP.md from the frontmatter of every
project Genesis and area dashboard, and enforces the context budget of
AGENTS.md section 4. Run it in the close ritual (skill /close).

    python3 .claude/skills/kb-frame/scripts/build_map.py   # Linux / macOS / web
    python  .claude/skills/kb-frame/scripts/build_map.py   # Windows, PowerShell

Run it from the target repo: the root is the git toplevel of the cwd.

Exit 1 and no MAP.md rewrite when a budget is broken:
  - frontmatter `next` longer than NEXT_MAX characters
  - a Genesis.md larger than GENESIS_HARD bytes (warning above GENESIS_SOFT)
  - NOW.md larger than NOW_MAX bytes
"""
import re
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kb_paths import AREAS, MAP, NOW, PROJECTS, ROOT  # noqa: E402

KEY = re.compile(r"^([a-z_]+):\s*(.*)$")

NEXT_MAX = 140        # characters
GENESIS_SOFT = 6000   # bytes -> warning
GENESIS_HARD = 8000   # bytes -> error
NOW_MAX = 4096        # bytes -> error


def read_frontmatter(path: Path):
    """Return the file's frontmatter as a dict, or None if it has none."""
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except (UnicodeDecodeError, OSError):
        return None
    if not lines or lines[0].strip() != "---":
        return None
    fm = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        m = KEY.match(line)
        if m:
            fm[m.group(1)] = m.group(2).strip().strip('"')
    if not fm:
        return None
    fm["path"] = path.relative_to(ROOT).as_posix()
    fm["name"] = path.parent.name
    fm["bytes"] = path.stat().st_size
    return fm


def collect():
    entries = []
    for folder in (PROJECTS, AREAS):
        if not folder.exists():
            continue
        for path in sorted(folder.rglob("*.md")):
            fm = read_frontmatter(path)
            if fm:
                entries.append(fm)
    return entries


def check_budget(entries):
    errors, warnings = [], []
    for e in entries:
        nxt = e.get("next", "")
        if len(nxt) > NEXT_MAX:
            errors.append(f"{e['path']}: next has {len(nxt)} chars (max {NEXT_MAX})")
        if e["path"].endswith("Genesis.md"):
            if e["bytes"] > GENESIS_HARD:
                errors.append(f"{e['path']}: {e['bytes']} B (max {GENESIS_HARD}). "
                              "Move history to Log.md / Decisions.md.")
            elif e["bytes"] > GENESIS_SOFT:
                warnings.append(f"{e['path']}: {e['bytes']} B (target {GENESIS_SOFT})")
    if NOW.exists():
        now_bytes = NOW.stat().st_size
        if now_bytes > NOW_MAX:
            errors.append(f"NOW.md: {now_bytes} B (max {NOW_MAX}). Trim it in the same pass.")
    else:
        errors.append(f"{NOW.relative_to(ROOT).as_posix()} is missing")
    return errors, warnings


def table(title, rows, label, with_next=True):
    if not rows:
        return []
    head = f"| {label} | Tier | Updated |" + (" Next |" if with_next else "")
    sep = "| :--- | :--- | :--- |" + (" :--- |" if with_next else "")
    out = [f"## {title}", "", head, sep]
    for r in sorted(rows, key=lambda r: r.get("updated", ""), reverse=True):
        row = f"| [{r['name']}]({r['path']}) | {r.get('tier', '')} | {r.get('updated', '')} |"
        if with_next:
            row += f" {r.get('next', '')} |"
        out.append(row)
    return out + [""]


def main():
    entries = collect()
    errors, warnings = check_budget(entries)
    for w in warnings:
        print(f"WARN  {w}")
    if errors:
        for e in errors:
            print(f"ERROR {e}")
        print("MAP.md NOT regenerated: fix the budget errors first.")
        return 1

    projects = [e for e in entries if e.get("type") == "project"]
    areas = [e for e in entries if e.get("type") == "area"]
    script = Path(__file__).resolve()
    try:
        script_rel = script.relative_to(ROOT).as_posix()
    except ValueError:
        script_rel = script.name

    md = [
        "# MAP — repository index",
        "",
        f"> **Generated by `{script_rel}`. Do not edit by hand.**",
        f"> Build: {datetime.now():%Y-%m-%d %H:%M}. If a row is wrong, the file's "
        "frontmatter is wrong: fix it there and rerun the script.",
        "",
        "---",
        "",
    ]
    md += table("Active projects (need decisions)",
                [p for p in projects if p.get("status") == "active"], "Project")
    md += table("Running (autonomous, only remembered)",
                [p for p in projects if p.get("status") == "running"], "Project")
    md += table("Parked (`next` lives in the Genesis)",
                [p for p in projects if p.get("status") == "parked"], "Project",
                with_next=False)
    md += table("Areas (life circles, no end state)", areas, "Area")
    md += ["---", "",
           f"*{len(projects)} projects - {len(areas)} areas. "
           "Live state: `NOW.md`. Rules: `AGENTS.md`.*"]

    MAP.parent.mkdir(parents=True, exist_ok=True)
    MAP.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"MAP.md regenerated: {len(projects)} projects, {len(areas)} areas, "
          f"{MAP.stat().st_size} B.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
